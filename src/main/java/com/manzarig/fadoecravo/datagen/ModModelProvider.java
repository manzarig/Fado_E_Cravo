package com.manzarig.fadoecravo.datagen;

import com.manzarig.fadoecravo.FadoECravo;
import com.manzarig.fadoecravo.block.RadioBlock;
import com.manzarig.fadoecravo.registry.ModBlocks;
import net.fabricmc.fabric.api.datagen.v1.FabricDataOutput;
import net.fabricmc.fabric.api.datagen.v1.provider.FabricModelProvider;
import net.minecraft.core.Direction;
import net.minecraft.data.models.BlockModelGenerators;
import net.minecraft.data.models.ItemModelGenerators;
import net.minecraft.data.models.blockstates.MultiVariantGenerator;
import net.minecraft.data.models.blockstates.PropertyDispatch;
import net.minecraft.data.models.blockstates.Variant;
import net.minecraft.data.models.blockstates.VariantProperties;
import net.minecraft.resources.ResourceLocation;

/**
 * Writes the blockstate of the radio and the model of its item. The block model {@code block/radio}
 * is generated by {@code tools/art/make_radio_model.py} and only referred to here. The block itself
 * is drawn by its GeckoLib renderer; the blockstate model gives the break particles and the item.
 */
public class ModModelProvider extends FabricModelProvider {
	private static final ResourceLocation RADIO_MODEL = FadoECravo.id("block/radio");

	public ModModelProvider(FabricDataOutput output) {
		super(output);
	}

	@Override
	public void generateBlockStateModels(BlockModelGenerators generators) {
		// One variant for every facing. ON and POWERED are left out: the renderer shows them.
		generators.blockStateOutput.accept(MultiVariantGenerator.multiVariant(ModBlocks.RADIO)
				.with(PropertyDispatch.property(RadioBlock.FACING)
						.generate(facing -> Variant.variant()
								.with(VariantProperties.MODEL, RADIO_MODEL)
								.with(VariantProperties.Y_ROT, rotationOf(facing)))));

		// The item looks like the radio that is switched off.
		generators.delegateItemModel(ModBlocks.RADIO, RADIO_MODEL);
	}

	@Override
	public void generateItemModels(ItemModelGenerators generators) {
		// The radio is a block item, whose model is written with the block above.
	}

	/** The models have their front on the north face, so a radio facing east is turned 90 degrees clockwise, and so on. */
	private static VariantProperties.Rotation rotationOf(Direction facing) {
		return switch (facing) {
			case EAST -> VariantProperties.Rotation.R90;
			case SOUTH -> VariantProperties.Rotation.R180;
			case WEST -> VariantProperties.Rotation.R270;
			default -> VariantProperties.Rotation.R0;
		};
	}
}
